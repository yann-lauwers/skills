"""The pages a session published, each resolved against the local artifact store for its second address."""
import json
import os
import re

# The local artifact store, and the port its LaunchAgent serves on. Both are read
# from the store's own `bin/artifact` nowhere — a second spelling of the port would
# hand back an address nothing answers on — so they are pinned here and asserted by
# the battery against that file.
ARTIFACT_STORE = os.environ.get("ARTIFACT_STORE_ROOT") or os.path.expanduser(
    "~/.local/share/claude-artifacts")
STORE_PORT = 4310
SEGMENT = r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}"
LOCAL_URL_RE = re.compile(r"http://127\.0\.0\.1:%d/(%s)/(%s)/" % (
    STORE_PORT, SEGMENT, SEGMENT))
ARTIFACT_ID_RE = re.compile(
    r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


def store_index():
    """The local store's own answer to "which page is this", read from its registries.

    `<group>/registry.json` is regenerated by every `artifact capture` and every
    `artifact publish`, so it is current at the seam without this hook parsing a
    manifest. Two maps come back because a page is reached by either address: the
    hosted id the tool returned, and the group/slug pair a local publish prints.

    An unreadable store yields empty maps, and empty means UNKNOWN here — a page
    still gets its hosted half, marked as having no local copy, rather than being
    dropped for want of the store.
    """
    by_id, by_slug = {}, {}
    try:
        groups = sorted(os.listdir(ARTIFACT_STORE))
    except Exception:
        return by_id, by_slug
    for group in groups:
        registry = os.path.join(ARTIFACT_STORE, group, "registry.json")
        try:
            with open(registry, errors="replace") as fh:
                data = json.load(fh)
        except Exception:
            continue
        rows = data.get("artifacts") if isinstance(data, dict) else None
        if not isinstance(rows, dict):
            continue
        for slug, row in rows.items():
            if not isinstance(row, dict):
                continue
            remotes = [r for r in (row.get("remote") or []) if isinstance(r, dict)]
            entry = {
                "group": group,
                "slug": slug,
                "title": row.get("title") if isinstance(row.get("title"), str) else slug,
                # The last remote is the current one: `capture` drops any row carrying
                # the same artifact id before appending, so the tail is the live pairing
                # and an earlier row is a page that was republished to a new id.
                "hosted": remotes[-1].get("url") if remotes else "",
            }
            by_slug[(group, slug)] = entry
            for remote in remotes:
                rid = remote.get("artifact_id")
                if isinstance(rid, str) and rid:
                    by_id[rid] = entry
    return by_id, by_slug


def served_url(entry):
    return "http://127.0.0.1:%d/%s/%s/" % (STORE_PORT, entry["group"], entry["slug"])


def pages_published(transcript, read_lines):
    """Every page this session published, each carrying BOTH of its addresses.

    Two observables, because this machine publishes two ways and the summary
    replaces the evidence for both. The Artifact tool's response object carries
    `url` + `artifact_id` + `path`; the local CLI prints the store directory, and
    the mirror hook prints the served URL. Either one identifies the page, and the
    store's registry supplies whatever the transcript did not say.

    A half is recorded as an empty string rather than omitted. "Published to the
    host with no local copy" is a fact the resumed session has to be able to read —
    it is the mirror having failed — and a page listed with one address and no note
    reads as a page that only ever had one.
    """
    if not transcript:
        return []
    by_id, by_slug = store_index()
    store_prefix = ARTIFACT_STORE.rstrip("/") + "/"
    store_re = re.compile(re.escape(store_prefix) + r"(%s)/(%s)\b" % (SEGMENT, SEGMENT))
    out, seen = [], set()

    def add(key, entry, hosted, title, source):
        if key in seen:
            return
        seen.add(key)
        out.append({
            "title": (entry or {}).get("title") or title or "",
            "hosted": hosted or (entry or {}).get("hosted") or "",
            "local": served_url(entry) if entry else "",
            "source": source or "",
        })

    # The cheap reject is built from the two markers a page's own addresses carry,
    # and the store prefix is one of them: keying it on the word "artifact" reads
    # the default install path rather than the configured one, so a store anywhere
    # else is rejected before it is ever looked at.
    markers = ("artifact_id", store_prefix, "127.0.0.1:%d" % STORE_PORT)

    for line in read_lines(transcript):
        if not any(marker in line for marker in markers):
            continue                    # cheap reject before paying for a parse
        try:
            row = json.loads(line)
        except Exception:
            continue
        if not isinstance(row, dict):
            continue

        result = row.get("toolUseResult")
        if isinstance(result, dict):
            rid = result.get("artifact_id")
            url = result.get("url")
            if (isinstance(rid, str) and ARTIFACT_ID_RE.fullmatch(rid)
                    and isinstance(url, str) and url):
                path = result.get("path")
                title = result.get("title")
                add(("id", rid), by_id.get(rid), url,
                    title if isinstance(title, str) else "",
                    path if isinstance(path, str) else "")

        # The local half, wherever it was printed: the served URL, or the store
        # directory a local publish echoes. Matched on the whole line so a hook
        # message and a command's stdout are read on the same terms.
        for group, slug in LOCAL_URL_RE.findall(line) + store_re.findall(line):
            entry = by_slug.get((group, slug))
            if entry is None:
                continue                # a directory that is not an artifact
            add(("slug", group, slug), entry, entry["hosted"], entry["title"], "")

    return out
